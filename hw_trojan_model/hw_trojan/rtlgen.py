"""Artifact generation for the ``hw_trojan`` component.

``generate(cfg, out_dir)`` writes, from the plan-configured parameters:
  coeffs.mem, trig_cos.mem, trig_sin.mem      data the RTL $readmemh-loads
  fir_core.v                                  clean recovered FIR (agent start point)
  fir_core_trojan.v                           Trigger-1 Trojan core (TROJAN_EN-gated)
  vec_in.mem / vec_clean.mem / vec_troj.mem   golden vectors from the DSP model
  tb_trojan.v                                 self-checking testbench (Icarus)
  params.vh                                   `defines shared by RTL + TB

The mem files and vectors come straight from ``dsp`` so the Verilog can never
drift from the verified golden model. The Verilog is synthesizable Verilog-2001;
run it on the OSS CAD Suite (iverilog) exactly as in Challenge 1.
"""
from __future__ import annotations

import os
import numpy as np

from .config import HWTrojanConfig
from . import dsp


def _mem(path, values, width=4):
    with open(path, "w") as f:
        for v in values:
            f.write("%0*X\n" % (width, int(v) & ((1 << (4 * width)) - 1)))


def generate(cfg: HWTrojanConfig, out_dir: str, audio: np.ndarray | None = None) -> dict:
    os.makedirs(out_dir, exist_ok=True)
    hq = dsp.design_coeffs(cfg)
    cos_q, sin_q = dsp.trig_tables(cfg)
    _mem(os.path.join(out_dir, "coeffs.mem"), hq)
    _mem(os.path.join(out_dir, "trig_cos.mem"), cos_q)
    _mem(os.path.join(out_dir, "trig_sin.mem"), sin_q)

    # golden vectors: short speech head, tone burst (arms), out-of-band tail
    head = (audio[: cfg.win * 8] if audio is not None and len(audio) >= cfg.win * 8
            else dsp.synth_speechlike(cfg.win * 8, cfg))
    burst = dsp.tone(cfg.win * (cfg.dwell + 2), cfg.f_trig, 0.15, cfg.fs)
    oob = dsp.tone(cfg.win * 3, 6500, 0.5, cfg.fs)
    stim = np.concatenate([head, burst, oob]).astype(np.int16)
    clean = dsp.fir_fixed(stim, hq, cfg)
    troj, armed_at, _ = dsp.run_trojan(stim, hq, cfg, trojan_en=True)
    _mem(os.path.join(out_dir, "vec_in.mem"), stim)
    _mem(os.path.join(out_dir, "vec_clean.mem"), clean)
    _mem(os.path.join(out_dir, "vec_troj.mem"), troj)

    with open(os.path.join(out_dir, "params.vh"), "w") as f:
        f.write("// auto-generated by hw_trojan.rtlgen -- do not edit\n")
        for k, v in [("NTAPS", cfg.ntaps), ("GD", cfg.group_delay), ("COEFFQ", cfg.coeff_q),
                     ("TABLEN", cfg.tab_len), ("WIN", cfg.win), ("DWELL", cfg.dwell),
                     ("RATIO_SHIFT", cfg.ratio_shift), ("NVEC", len(stim)),
                     ("ARMED_AT", armed_at if armed_at is not None else -1)]:
            f.write("`define %s %d\n" % (k, v))

    with open(os.path.join(out_dir, "fir_core.v"), "w") as f:
        f.write(_fir_core_v(cfg, trojan=False))
    with open(os.path.join(out_dir, "fir_core_trojan.v"), "w") as f:
        f.write(_fir_core_v(cfg, trojan=True))
    with open(os.path.join(out_dir, "tb_trojan.v"), "w") as f:
        f.write(_tb_v(cfg))

    return {"coeffs": len(hq), "tab_len": cfg.tab_len, "nvec": len(stim),
            "armed_at": armed_at, "out_dir": os.path.abspath(out_dir)}


# --------------------------------------------------------------------- Verilog
def _fir_core_v(cfg: HWTrojanConfig, trojan: bool) -> str:
    name = "fir_core_trojan" if trojan else "fir_core"
    gd = cfg.group_delay
    troj_ports = ""
    troj_decls = ""
    troj_logic = ""
    out_sel = "y_fir"
    if trojan:
        troj_decls = f"""
    // ---- Trigger 1: out-of-band tone detector + dwell + latching arm ----
    reg  signed [15:0] cosm [0:`TABLEN-1];
    reg  signed [15:0] sinm [0:`TABLEN-1];
    initial begin
        $readmemh("trig_cos.mem", cosm);
        $readmemh("trig_sin.mem", sinm);
    end
    reg  [$clog2(`TABLEN)-1:0] kph;
    reg  [$clog2(`WIN)-1:0]    wcnt;
    reg  signed [47:0] accI, accQ;
    reg         [47:0] accE;
    reg         [7:0]  dwell;
    reg                armed;
    // group-delay delay line for the bypass payload
    reg  signed [15:0] xd [0:{gd}-1];
    integer di;
    wire signed [31:0] pI = $signed(x) * cosm[kph];
    wire signed [31:0] pQ = $signed(x) * sinm[kph];
    wire signed [31:0] pE = $signed(x) * $signed(x);
    // window-close quantities (combinational on the registered accumulators + current sample)
    wire signed [47:0] nI = accI + pI;
    wire signed [47:0] nQ = accQ + pQ;
    wire        [47:0] nE = accE + pE;
    wire signed [23:0] Is = nI >>> `COEFFQ;
    wire signed [23:0] Qs = nQ >>> `COEFFQ;
    wire        [47:0] bp = (Is*Is) + (Qs*Qs);
    wire               win_close = (wcnt == `WIN-1);
    wire               fires = win_close && (bp > (nE <<< `RATIO_SHIFT));
    wire               arm_now = armed || (fires && (dwell + 1 >= `DWELL));
"""
        troj_logic = f"""
            // detector / dwell / arm update (must settle before out is chosen)
            if (in_valid) begin
                if (win_close) begin
                    if (bp > (nE <<< `RATIO_SHIFT)) dwell <= dwell + 1'b1;
                    else                            dwell <= 8'd0;
                    if (fires && (dwell + 1 >= `DWELL)) armed <= 1'b1;
                    accI <= 48'd0; accQ <= 48'd0; accE <= 48'd0; wcnt <= 0;
                end else begin
                    accI <= nI; accQ <= nQ; accE <= nE; wcnt <= wcnt + 1'b1;
                end
                kph <= (kph == `TABLEN-1) ? 0 : kph + 1'b1;
                for (di = {gd}-1; di > 0; di = di - 1) xd[di] <= xd[di-1];
                xd[0] <= x;
            end
"""
        out_sel = "(TROJAN_EN && arm_now) ? " + ("xd[%d-1]" % gd) + " : y_fir"
    return f"""// {name}.v  -- auto-generated by hw_trojan.rtlgen (mirrors dsp.py golden model)
// Linear-phase Q1.15 FIR. {"Trigger-1 Trojan: out-of-band tone -> bypass, gated by TROJAN_EN." if trojan else "Clean recovered filter (agent start point)."}
`include "params.vh"
module {name} #(
    parameter TROJAN_EN = {1 if trojan else 0}
)(
    input  wire               clk,
    input  wire               rst_n,
    input  wire               in_valid,
    input  wire signed [15:0] x,
    output reg  signed [15:0] y,
    output reg                out_valid
);
    reg signed [15:0] coef [0:`NTAPS-1];
    reg signed [15:0] buf  [0:`NTAPS-1];
    integer i;
    initial $readmemh("coeffs.mem", coef);

    // FIR over {{x, buf[0..N-2]}} == same ordering as the golden model
    reg signed [47:0] acc;
    always @* begin
        acc = $signed(x) * coef[0];
        for (i = 1; i < `NTAPS; i = i + 1)
            acc = acc + $signed(buf[i-1]) * coef[i];
    end
    wire signed [47:0] acc_r = acc + (48'sd1 <<< (`COEFFQ-1));   // round half up
    wire signed [47:0] acc_s = acc_r >>> `COEFFQ;
    wire signed [15:0] y_fir =
        (acc_s >  16'sh7FFF) ? 16'sh7FFF :
        (acc_s < -16'sh8000) ? -16'sh8000 : acc_s[15:0];
{troj_decls}
    always @(posedge clk) begin
        if (!rst_n) begin
            for (i = 0; i < `NTAPS; i = i + 1) buf[i] <= 16'sd0;
            y <= 16'sd0; out_valid <= 1'b0;
            {"kph<=0; wcnt<=0; accI<=0; accQ<=0; accE<=0; dwell<=0; armed<=0; for(di=0;di<%d;di=di+1) xd[di]<=0;" % gd if trojan else ""}
        end else begin
            out_valid <= in_valid;
{troj_logic}
            if (in_valid) begin
                y <= {out_sel};
                for (i = `NTAPS-1; i > 0; i = i - 1) buf[i] <= buf[i-1];
                buf[0] <= x;
            end
        end
    end
endmodule
"""


def _tb_v(cfg: HWTrojanConfig) -> str:
    return """// tb_trojan.v  -- auto-generated self-checking testbench (Icarus Verilog)
// Streams vec_in.mem through a clean twin (TROJAN_EN=0) and a Trojaned twin
// (TROJAN_EN=1) and checks: clean twin == vec_clean.mem for EVERY sample
// (baseline), and Trojaned twin == vec_troj.mem (arms on the tone, then bypass).
`timescale 1ns/1ps
`include "params.vh"
module tb_trojan;
    reg clk=0, rst_n=0, in_valid=0;
    reg  signed [15:0] xin;
    wire signed [15:0] yc, yt;
    wire vc, vt;
    always #5 clk = ~clk;

    fir_core        #(.TROJAN_EN(0)) uClean (.clk(clk),.rst_n(rst_n),.in_valid(in_valid),.x(xin),.y(yc),.out_valid(vc));
    fir_core_trojan #(.TROJAN_EN(1)) uTroj  (.clk(clk),.rst_n(rst_n),.in_valid(in_valid),.x(xin),.y(yt),.out_valid(vt));

    reg signed [15:0] vin   [0:`NVEC-1];
    reg signed [15:0] vclean[0:`NVEC-1];
    reg signed [15:0] vtroj [0:`NVEC-1];
    integer n, errc, errt, oc, ot;
    initial begin
        $readmemh("vec_in.mem", vin);
        $readmemh("vec_clean.mem", vclean);
        $readmemh("vec_troj.mem", vtroj);
        errc=0; errt=0; oc=0; ot=0;
        @(negedge clk); rst_n=1;
        for (n=0; n<`NVEC; n=n+1) begin
            @(negedge clk); in_valid=1; xin=vin[n];
            @(posedge clk);                 // out_valid asserts for this sample
            #1;
            if (vc) begin
                if (yc !== vclean[oc]) begin errc=errc+1;
                    if (errc<=5) $display("CLEAN mismatch @%0d: got %0d exp %0d", oc, yc, vclean[oc]); end
                oc=oc+1;
            end
            if (vt) begin
                if (yt !== vtroj[ot]) begin errt=errt+1;
                    if (errt<=5) $display("TROJ  mismatch @%0d: got %0d exp %0d", ot, yt, vtroj[ot]); end
                ot=ot+1;
            end
        end
        @(negedge clk); in_valid=0;
        $display("checked clean=%0d troj=%0d  errors clean=%0d troj=%0d", oc, ot, errc, errt);
        if (errc==0 && errt==0 && oc==`NVEC && ot==`NVEC)
            $display("TB_TROJAN: ALL PASS");
        else
            $display("TB_TROJAN: FAIL");
        $finish;
    end
endmodule
"""
